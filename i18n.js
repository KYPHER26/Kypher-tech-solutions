// ---------- language switching ----------
function applyLanguage(lang) {
  const dict = translations[lang];
  if (!dict) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  document.documentElement.setAttribute('lang', lang);
  localStorage.setItem('kypher-lang', lang);

  const toggle = document.getElementById('langToggle');
  if (toggle) toggle.setAttribute('data-lang', lang);
}

function initLanguage() {
  const saved = localStorage.getItem('kypher-lang') || 'en';
  applyLanguage(saved);

  const toggle = document.getElementById('langToggle');
  if (toggle) {
    toggle.addEventListener('click', () => {
      const current = toggle.getAttribute('data-lang') === 'sw' ? 'sw' : 'en';
      applyLanguage(current === 'en' ? 'sw' : 'en');
    });
  }
}

initLanguage();
